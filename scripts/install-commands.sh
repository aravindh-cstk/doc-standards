#!/usr/bin/env bash
# Links the repo's slash commands into an agent's own command folder.
#
# Claude Code users should install the plugin instead (see .claude/README.md).
# This script covers the rest: Claude Code without the plugin, the fallback
# setup script for Claude Code on the web, Codex and Cursor.
#
# Why links rather than copies: a repository-local .claude/commands/ is only
# discovered when an agent starts inside this repository, but these commands
# are used while working in a consuming docs repository. The link makes them
# reachable everywhere while this folder stays the git-tracked source of truth.
# Codex has no command folder, so it gets one generated skill per command, each
# pointing back at the command file here rather than copying it.
#
# Every run also links ~/.doc-standards to this checkout. It is the last place
# the commands' shared resolver looks, so a command finds the toolchain from
# any folder on the machine.
#
# Idempotent. Re-run after adding a command. Pass --tool=claude|codex|cursor
# (default claude), --dry-run to see what it would do, and --uninstall to
# remove what it made.

set -euo pipefail

REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
SRC="$REPO/.claude/commands"
LINK="${DOC_STANDARDS_LINK:-$HOME/.doc-standards}"
MARKER="<!-- Generated by doc-standards scripts/install-commands.sh. Re-run that script rather than editing this file. -->"

TOOL=claude
DRY_RUN=0
UNINSTALL=0
for arg in "$@"; do
  case "$arg" in
    --tool=*) TOOL="${arg#--tool=}" ;;
    --dry-run) DRY_RUN=1 ;;
    --uninstall) UNINSTALL=1 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

case "$TOOL" in
  claude) DEST="${CLAUDE_COMMANDS_DIR:-$HOME/.claude/commands}" ;;
  cursor) DEST="${CURSOR_COMMANDS_DIR:-$HOME/.cursor/commands}" ;;
  codex) DEST="${CODEX_HOME:-$HOME/.codex}/skills" ;;
  *) echo "Unknown tool: $TOOL. Use claude, codex or cursor." >&2; exit 2 ;;
esac

[ -d "$SRC" ] || { echo "No commands at $SRC" >&2; exit 2; }

run() {
  if [ "$DRY_RUN" -eq 1 ]; then echo "would: $*"; else "$@"; fi
}

# The first paragraph under a command's H1, joined onto one line. Codex shows
# it as the skill description and uses it to decide when the skill applies.
summary() {
  awk 'NR > 1 && NF { found = 1; printf "%s%s", sep, $0; sep = " "; next } found { exit }' "$1"
}

codex_skill() {
  local name=$1 src=$2 desc
  desc=$(summary "$src" | sed 's/\\/\\\\/g; s/"/\\"/g')
  cat <<EOF
---
name: $name
description: "$desc"
---

$MARKER

Read \`$src\` and follow it step by step. Wherever it says \`\$ARGUMENTS\`, use the path or text the
user gave with this request. When the user gave none, do what the command says to do for a missing
argument.
EOF
}

# --- ~/.doc-standards ------------------------------------------------------

link_checkout() {
  if [ -e "$LINK" ] && [ "$(cd "$LINK" && pwd -P)" = "$(cd "$REPO" && pwd -P)" ]; then
    return
  fi
  if [ -L "$LINK" ]; then
    run rm "$LINK"
  elif [ -e "$LINK" ]; then
    echo "Leaving $LINK alone: it exists and is not this checkout. Commands outside a doc-standards folder will not find the toolchain until you move it aside and re-run." >&2
    return
  fi
  run ln -s "$REPO" "$LINK"
  echo "Linked $LINK to $REPO"
}

# --- install and uninstall -------------------------------------------------

linked=0
skipped=0
backed_up=0
removed=0

[ "$UNINSTALL" -eq 1 ] || { run mkdir -p "$DEST"; link_checkout; }

for src in "$SRC"/*.md; do
  name=$(basename "$src" .md)
  # A README documents a folder. It is not a command.
  [ "$name" = "README" ] && continue

  if [ "$TOOL" = "codex" ]; then
    dir="$DEST/$name"
    skill="$dir/SKILL.md"
    ours=0
    [ -f "$skill" ] && grep -qF "$MARKER" "$skill" && ours=1

    if [ "$UNINSTALL" -eq 1 ]; then
      if [ "$ours" -eq 1 ]; then
        run rm "$skill"
        run rmdir "$dir" 2>/dev/null || true
        removed=$((removed + 1))
      fi
      continue
    fi

    if [ -e "$dir" ] && [ "$ours" -eq 0 ]; then
      echo "Skipping $dir: a skill with that name already exists and this script did not create it." >&2
      continue
    fi
    content=$(codex_skill "$name" "$src")
    if [ "$ours" -eq 1 ] && [ "$(cat "$skill")" = "$content" ]; then
      skipped=$((skipped + 1))
      continue
    fi
    if [ "$DRY_RUN" -eq 1 ]; then
      echo "would: write $skill"
    else
      mkdir -p "$dir"
      printf '%s\n' "$content" > "$skill"
    fi
    linked=$((linked + 1))
    continue
  fi

  target="$DEST/$name.md"

  if [ "$UNINSTALL" -eq 1 ]; then
    if [ -L "$target" ] && [ "$(readlink "$target")" = "$src" ]; then
      run rm "$target"
      removed=$((removed + 1))
    fi
    continue
  fi

  if [ -L "$target" ]; then
    if [ "$(readlink "$target")" = "$src" ]; then
      skipped=$((skipped + 1))
      continue
    fi
    run rm "$target"
  elif [ -e "$target" ]; then
    # A real file, so it predates this repo's copy. Keep it rather than
    # destroying an edit somebody made in place.
    backup="$target.pre-install.bak"
    if [ -e "$backup" ]; then
      echo "Refusing to overwrite the existing backup at $backup. Move it aside and re-run." >&2
      exit 1
    fi
    echo "Backing up $target to $backup"
    run mv "$target" "$backup"
    backed_up=$((backed_up + 1))
  fi

  run ln -s "$src" "$target"
  linked=$((linked + 1))
done

if [ "$UNINSTALL" -eq 1 ]; then
  echo "Removed $removed $TOOL command(s) from $DEST"
  echo "Any .pre-install.bak file is still there. Restore it by hand if you want the old copy back."
  echo "$LINK is still in place for the other agents. Remove it by hand once nothing uses it."
  exit 0
fi

echo "Installed $linked, already current $skipped, backed up $backed_up, into $DEST"
case "$TOOL" in
  claude) echo "Run /doc-gate or any command from any repository now." ;;
  cursor) echo "Run /fix-docs or any command from Cursor's chat in any repository now." ;;
  codex) echo "Start a new Codex session, then name a skill such as \$fix-docs." ;;
esac
